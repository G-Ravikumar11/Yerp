import { api, clickText, fill, launch, open, setValue, signIn, sleep, toastsGone, waitForToast } from './lib.mjs'

// The maintenance schedule on the machine form: the three interval types, the live summary, the checks, saving it, the
// register and dashboard reading the same status, a service completed and the clock starting again, and the history.
const { page, check, done } = await launch({ allow: [/400 POST \/api\/assets .*Check the year/] })
await signIn(page)
const stamp = Date.now().toString().slice(-6)
const name = `QA Loader ${stamp}`
const iso = (n) => { const d = new Date(); d.setDate(d.getDate() + n); return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}` }
const has = (sel) => page.evaluate((s) => !!document.querySelector(s), sel)
const summary = () => page.$eval('[aria-label="Schedule summary"]', (e) => e.textContent.replace(/\s+/g, ' ').trim())
const gone = () => page.waitForFunction(() => !document.querySelector('[role=dialog]'), { timeout: 10000 })
const row = (n = name) => page.evaluate((n) => [...document.querySelectorAll('table[aria-label=Machines] tbody tr')].find((r) => r.textContent.includes(n))?.textContent.replace(/\s+/g, ' ') ?? '', n)
const press = (label, n = name) => page.evaluate((n, label) => [...[...document.querySelectorAll('table[aria-label=Machines] tbody tr')].find((r) => r.textContent.includes(n)).querySelectorAll('button')].find((b) => b.textContent.trim() === label).click(), n, label)
const saveDisabled = () => page.evaluate(() => [...document.querySelectorAll('[role=dialog] button')].find((b) => b.textContent.trim() === 'Save the machine').disabled)

await open(page, '/projects/equipment?tab=register')
await page.waitForSelector('main h1')
await clickText(page, 'main button', 'Machine')
await page.waitForSelector('#mc-name')
await fill(page, '#mc-name', name)

// One section, one selector - and only the fields the type needs.
check('the schedule is one section with an interval type', await has('fieldset[aria-label="Maintenance schedule"] #mc-itype'))
check('meter + calendar shows both sets of fields', (await has('#mc-every')) && (await has('#mc-days')) && (await has('#mc-lastmeter')) && (await has('#mc-lastsvc')))
await setValue(page, '#mc-itype', 'Meter')
check('meter only hides the calendar fields', (await has('#mc-every')) && !(await has('#mc-days')) && !(await has('#mc-lastsvc')))
await setValue(page, '#mc-itype', 'Days')
check('calendar only hides the meter fields', !(await has('#mc-every')) && !(await has('#mc-lastmeter')) && (await has('#mc-days')))
await setValue(page, '#mc-unit', 'Km')
await setValue(page, '#mc-itype', 'Meter')
check('the meter unit follows the machine: kilometres', /\(km\)/.test(await page.$eval('label[for=mc-every]', (l) => l.textContent)))
await setValue(page, '#mc-unit', 'Hours')

// Meter + calendar, with numbers that put it inside the reminder window on the meter.
await setValue(page, '#mc-itype', 'Both')
await fill(page, '#mc-meter', '1000')
await fill(page, '#mc-every', '250')
await fill(page, '#mc-lastmeter', '760')
await fill(page, '#mc-days', '90')
await setValue(page, '#mc-lastsvc', '0923-02-20')
await sleep(200)
check('a mistyped year is caught on the form', (await saveDisabled()) && /Check the year/.test(await page.$eval('fieldset', (f) => f.textContent)))
await setValue(page, '#mc-lastsvc', iso(-20))
await sleep(300)
const s1 = await summary()
check('the live summary gives the threshold reached first and the status', /Due soon/.test(s1) && /at 1,010 hours or on/.test(s1) && /whichever comes first/.test(s1) && /10 hours to go/.test(s1), s1)
await fill(page, '#mc-remmeter', '300')
await sleep(200)
check('an early reminder longer than the interval is refused before saving', (await saveDisabled()) && /Fewer than 250 hours/.test(await page.$eval('fieldset', (f) => f.textContent)))
await fill(page, '#mc-remmeter', '20')
await fill(page, '#mc-lastmeter', '1200')
await sleep(200)
check('a last-service reading above the meter is refused', (await saveDisabled()) && /cannot have been serviced at 1200/.test(await page.$eval('fieldset', (f) => f.textContent)))
await fill(page, '#mc-lastmeter', '760')
await sleep(200)
check('a reminder of 20 h: 10 h to go is now inside it', /Due soon/.test(await summary()) && /Reminder from 990 hours/.test(await summary()), await summary())
await clickText(page, '[role=dialog] button', 'Save the machine')
await waitForToast(page, 'saved')
await gone()
await sleep(700)
check('the register shows the same status and the next threshold', /Due soon/.test(await row()) && /Next 1,010 hours or/.test(await row()), await row())
await toastsGone(page)

// Completing the service starts the clock again from it.
await press('Service done')
await page.waitForSelector('#sd-work')
await fill(page, '#sd-meter', '1005')
await fill(page, '#sd-work', '250 h service - oil, filters, greasing')
await fill(page, '#sd-parts', 'Engine oil 15 L, oil filter')
await fill(page, '#sd-pc', '8500')
await sleep(200)
check('the completion form shows when the next one falls due', /at 1,255 hours or on/.test(await page.$eval('[role=dialog]', (d) => d.textContent)))
await clickText(page, '[role=dialog] button', 'Record the service')
await waitForToast(page, 'Next due')
await gone()
await sleep(700)
check('after the service: upcoming, next at 1,255 hours', /Upcoming/.test(await row()) && /Next 1,255 hours/.test(await row()) && !/Service done/.test(await row()), await row())
await toastsGone(page)

await clickText(page, 'table[aria-label=Machines] tbody button', name)
await page.waitForSelector('table[aria-label=Services] tbody tr')
const hist = await page.$eval('table[aria-label=Services]', (t) => t.textContent)
check('the service history has the date, reading, work, parts, cost and next due', /1005/.test(hist) && /oil, filters/.test(hist) && /Engine oil/.test(hist) && /8,500/.test(hist) && /1,255 hours/.test(hist), hist.slice(0, 300))
const trail = await page.$eval('[aria-label="Schedule changes"]', (t) => t.textContent)
check('the schedule changes are kept', /Service completed/.test(trail) && /Schedule set/.test(trail), trail.slice(0, 200))
await clickText(page, 'section button', 'Close')

// Editing: switch it to calendar only.
await press('Edit')
await page.waitForSelector('#mc-itype')
await setValue(page, '#mc-itype', 'Days')
await sleep(200)
check('calendar only: the summary is a date only', /Next service due on/.test(await summary()) && !/hours or/.test(await summary()), await summary())
await clickText(page, '[role=dialog] button', 'Save the machine')
await waitForToast(page, 'saved')
await gone()
await sleep(700)
check('the register follows the edit', /Upcoming/.test(await row()) && !/Next 1,255/.test(await row()), await row())

// An overdue machine, set up through the API, reads Overdue on the register and the dashboard.
const late = `QA Mixer ${stamp}`
const bad = await api(page, 'POST', '/api/assets', { name: `${late} old`, service_interval_type: 'Days', service_every_days: 90, last_service_on: '0923-02-20' })
check('the server refuses a mistyped year too', bad.status === 400 && /Check the year/.test(JSON.stringify(bad.data)), JSON.stringify(bad))
const made = await api(page, 'POST', '/api/assets', { name: late, service_interval_type: 'Days', service_every_days: 90, last_service_on: iso(-100) })
check('the overdue machine is set up', made.status === 200 && made.data.service.status === 'Overdue', JSON.stringify(made).slice(0, 300))
// The register is kept in the browser between visits; drop it, so the page reads the server afresh.
await page.evaluate(() => new Promise((r) => { const q = indexedDB.deleteDatabase('keyval-store'); q.onsuccess = q.onerror = q.onblocked = () => r() }))
await open(page, '/projects/equipment?tab=register')
await page.waitForFunction((n) => [...document.querySelectorAll('table[aria-label=Machines] tbody tr')].some((r) => r.textContent.includes(n)), { timeout: 15000 }, late)
check('overdue on the register, with Service done offered', /Overdue/.test(await row(late)) && /Service done/.test(await row(late)), await row(late))
await open(page, '/projects/equipment')
await page.waitForSelector('main')
await page.waitForFunction(() => /Services overdue or due/.test(document.body.textContent), { timeout: 15000 })
const dash = await page.evaluate(() => document.body.textContent.replace(/\s+/g, ' '))
check('the dashboard counts it and lists it as overdue', /Services overdue or due/.test(dash) && new RegExp(`Overdue\\s*\\S*\\s*${late}|${late}`).test(dash) && /10 days past its service/.test(dash))
await done()
