import { api, clickText, fill, launch, open, setValue, signIn, sleep, toastsGone, waitForToast } from './lib.mjs'

// Equipment & Plant through the screens: the dashboard, allocating an operator, logging a shift, fuel, a breakdown,
// a hire agreement taken to its return, an expense, and the reports - each checked against what the server then holds.
const { page, check, done } = await launch({ allow: [/409 POST \/api\/plant/] })
await signIn(page)
const stamp = Date.now().toString().slice(-6)
const day = (n) => new Date(Date.now() + n * 864e5).toISOString().slice(0, 10)
const text = (sel) => page.$eval(sel, (e) => e.textContent.replace(/\s+/g, ' ').trim())
const top = (label) => page.evaluate((label) => {
  const d = [...document.querySelectorAll('[role=dialog]')].pop()
  const b = [...(d?.querySelectorAll('button') ?? [])].find((x) => x.textContent.trim().startsWith(label))
  b?.click()
  return !!b
}, label).then((ok) => { if (!ok) throw new Error(`no button ${label}`) })
const tab = async (label) => { await clickText(page, '[role=tab]', label); await sleep(700) }
const pick = (sel, re) => page.$eval(sel, (s, re) => [...s.options].find((o) => new RegExp(re).test(o.textContent))?.value, re).then((v) => setValue(page, sel, v))

// Setup the screens do not need to show: a project, two machines (one hired in), two employees.
await open(page, '/projects/equipment')
const job = (await api(page, 'POST', '/api/jobs', { name: `Plant site ${stamp}`, customer_name: 'E2E' })).data
const jcb = (await api(page, 'POST', '/api/assets', { name: `JCB ${stamp}`, category: 'Earthmoving', meter_reading: 500, service_every: 250 })).data
const crane = (await api(page, 'POST', '/api/assets', { name: `Crane ${stamp}`, category: 'Lifting', ownership: 'Rented', hire_rate: 1, hire_basis: 'Day' })).data
await api(page, 'POST', `/api/assets/${jcb.id}/move`, { to_job_id: job.id })
const emp = (n, ph) => api(page, 'POST', '/api/employees', { first_name: n, last_name: `Op${stamp}`, email: `${n.toLowerCase()}.${stamp}@example.in`, password: 'Passw0rd-QA1', phone: ph, job_title: 'Operator', department_id: null, reports_to: null, level: 'L1', role: 'employee', permission_role: 'staff', site_ids: [], employment_type: 'full_time', pay_frequency: 'monthly', salary: 20800, tax_rate: 0, start_date: '2026-01-01', emergency_contact: '', emergency_phone: '' }).then((r) => r.data)
const ravi = await emp('Ravi', '9876501234')
await emp('Anil', '9876509999')
await page.evaluate(() => indexedDB.deleteDatabase('keyval-store'))
await open(page, '/projects/equipment')

check('the page opens on the dashboard with its cards', /Total equipment/.test(await text('main')) && /Fuel expenditure/.test(await text('main')) && /Rental returns/.test(await text('main')))

// allocate an operator through the form
await tab('Allocation')
await clickText(page, 'main button', 'Allocate')
await page.waitForSelector('#al-m')
await page.waitForFunction((c) => [...document.querySelectorAll('#al-m option')].some((o) => o.textContent.includes(c)), { timeout: 15000 }, jcb.code)
await pick('#al-m', jcb.code)
await page.waitForFunction(() => [...document.querySelectorAll('#al-e option')].some((o) => /Ravi/.test(o.textContent)), { timeout: 15000 })
await pick('#al-e', `Ravi Op${stamp}`)
await sleep(300)
check('choosing the employee shows their mobile from HR', /9876501234/.test(await text('[role=dialog]')))
await top('Allocate')
await waitForToast(page, 'is on')
await toastsGone(page)
await page.waitForFunction(() => /9876501234/.test(document.querySelector('table[aria-label=Allocations]')?.textContent ?? ''), { timeout: 10000 })
check('the allocation lists the machine, the operator and their mobile', /Ravi/.test(await text('table[aria-label=Allocations]')) && /Operator/.test(await text('table[aria-label=Allocations]')))

// log a shift through the form: the sums appear as it is typed
await tab('Logbook')
await clickText(page, 'main button', 'Log a shift')
await page.waitForSelector('#lb-m')
await page.waitForFunction((c) => [...document.querySelectorAll('#lb-m option')].some((o) => o.textContent.includes(c)), { timeout: 15000 }, jcb.code)
await pick('#lb-m', jcb.code)
await pick('#lb-e', `Ravi Op${stamp}`)
await setValue(page, '#lb-d', day(-1))
await setValue(page, '#lb-st', '07:00')
await setValue(page, '#lb-et', '19:00')
await fill(page, '#lb-b', '60')
await fill(page, '#lb-om', '500')
await fill(page, '#lb-cm', '508')
await sleep(300)
check('the form works out 11 h on duty and 8 h running as it is typed', /On duty 11 h/.test(await text('[role=dialog]')) && /machine running 8 h/.test(await text('[role=dialog]')))
await top('Log the shift')
await waitForToast(page, 'Logged')
await toastsGone(page)
const lg = (await api(page, 'GET', '/api/plant/logs')).data.logs[0]
check('the shift is saved: 11 h duty, 3 overtime, 8 machine hours', lg.attendance_hours === 11 && lg.overtime_hours === 3 && lg.operating_hours === 8, JSON.stringify([lg.attendance_hours, lg.overtime_hours, lg.operating_hours]))
await page.waitForFunction(() => [...document.querySelectorAll('table[aria-label=Logbook] button')].some((b) => b.textContent.trim() === 'Approve'), { timeout: 10000 })
await page.evaluate(() => [...document.querySelectorAll('table[aria-label=Logbook] button')].find((b) => b.textContent.trim() === 'Approve').click())
await waitForToast(page, 'approved')
await toastsGone(page)
check('the supervisor approves the day', (await api(page, 'GET', '/api/plant/logs')).data.logs[0].approval_status === 'Approved')

// fuel through the form
await tab('Fuel')
await clickText(page, 'main button', 'Record fuel')
await page.waitForSelector('#fl-m')
await page.waitForFunction((c) => [...document.querySelectorAll('#fl-m option')].some((o) => o.textContent.includes(c)), { timeout: 15000 }, jcb.code)
await pick('#fl-m', jcb.code)
await setValue(page, '#fl-d', day(-1))
await fill(page, '#fl-l', '40')
await fill(page, '#fl-r', '90')
await fill(page, '#fl-v', `FV-${stamp}`)
await sleep(200)
check('the total cost is worked out as it is typed', /3,600/.test(await page.$eval('#fl-a', (e) => e.value)))
await top('Record fuel')
await waitForToast(page, 'FUEL-')
await toastsGone(page)
await page.waitForFunction(() => /L \/ h/.test(document.body.textContent), { timeout: 10000 })
check('fuel by machine shows 5 litres an hour', /5/.test(await text('table[aria-label="Fuel by machine"]')))

// a breakdown through the form takes the machine off work
await tab('Maintenance')
await clickText(page, 'main button', 'Report or schedule')
await page.waitForSelector('#mr-m')
await page.waitForFunction((c) => [...document.querySelectorAll('#mr-m option')].some((o) => o.textContent.includes(c)), { timeout: 15000 }, jcb.code)
await pick('#mr-m', jcb.code)
await setValue(page, '#mr-k', 'Emergency')
await fill(page, '#mr-d', 'Hydraulic hose burst')
await page.evaluate(() => [...document.querySelectorAll('[role=dialog] input[type=checkbox]')].pop().click())
await top('Raise it')
await waitForToast(page, 'off work')
await toastsGone(page)
check('the machine shows as broken down', (await api(page, 'GET', `/api/assets/${jcb.id}`)).data.status === 'Breakdown' && /Breakdown/.test(await text('table[aria-label=Maintenance]')))
await page.evaluate(() => [...document.querySelectorAll('table[aria-label=Maintenance] button')].find((b) => b.textContent.trim() === 'Complete').click())
await page.waitForSelector('#mc-w')
await fill(page, '#mc-w', 'Hose replaced')
await fill(page, '#mc-pc', '4500')
await top('Complete the job')
await waitForToast(page, 'completed')
await toastsGone(page)
check('completing it puts the machine back to work', (await api(page, 'GET', `/api/assets/${jcb.id}`)).data.status === 'Deployed')

// a hire agreement: provider, agreement, invoice, return
await api(page, 'POST', `/api/assets/${crane.id}/move`, { to_job_id: job.id })
await tab('Rentals')
await clickText(page, 'main button', 'Providers')
await page.waitForSelector('[role=dialog]')
await top('Provider')
await page.waitForSelector('#pv-n')
await fill(page, '#pv-n', `Sai Cranes ${stamp}`)
await fill(page, '#pv-m', '9849012345')
await top('Save')
await waitForToast(page, 'added')
await toastsGone(page)
await page.keyboard.press('Escape')
await sleep(400)
await clickText(page, 'main button', 'Hire agreement')
await page.waitForSelector('#rn-m')
await page.waitForFunction((c) => [...document.querySelectorAll('#rn-m option')].some((o) => o.textContent.includes(c)), { timeout: 15000 }, crane.code)
check('only machines hired in are offered for an agreement', !(await page.$$eval('#rn-m option', (o) => o.map((x) => x.textContent).join())).includes(jcb.code))
await pick('#rn-m', crane.code)
await page.waitForFunction((n) => [...document.querySelectorAll('#rn-p option')].some((o) => o.textContent.includes(n)), { timeout: 15000 }, `Sai Cranes ${stamp}`)
await pick('#rn-p', `Sai Cranes ${stamp}`)
await fill(page, '#rn-a', `SC/${stamp}`)
await setValue(page, '#rn-s', day(-10))
await setValue(page, '#rn-r', day(5))
await fill(page, '#rn-rate', '1800')
await setValue(page, '#rn-b', 'Hourly')
await top('Record the agreement')
await waitForToast(page, 'RNT-')
await toastsGone(page)
await page.waitForFunction((a) => document.querySelector('table[aria-label=Rentals]')?.textContent.includes(a), { timeout: 10000 }, `SC/${stamp}`)
await page.evaluate((a) => [...document.querySelectorAll('table[aria-label=Rentals] button')].find((b) => b.textContent.includes(a)).click(), `SC/${stamp}`)
await page.waitForFunction(() => /Agreement history/.test(document.body.textContent), { timeout: 10000 })
await top('Add invoice')
await page.waitForSelector('#ri-n')
await fill(page, '#ri-n', `SCI-${stamp}`)
await fill(page, '#ri-a', '18000')
await fill(page, '#ri-p', '5000')
await top('Record the invoice')
await waitForToast(page, 'outstanding')
await toastsGone(page)
const rent = (await api(page, 'GET', '/api/plant/rentals')).data.rentals.find((r) => r.agreement_no === `SC/${stamp}`)
check('the invoice leaves 13,000 outstanding', rent.outstanding === 13000, String(rent.outstanding))
await page.waitForFunction(() => [...document.querySelectorAll('[role=dialog] button')].some((b) => b.textContent.trim() === 'Return the machine'), { timeout: 10000 })
await top('Return the machine')
await page.waitForSelector('#rt-on')
await top('Yes')
await waitForToast(page, 'returned')
await toastsGone(page)
const cr = (await api(page, 'GET', `/api/assets/${crane.id}`)).data
check('returned: off its site, shown Returned, and refused for allocation', cr.status === 'Returned' && !cr.current_job_id && (await api(page, 'POST', '/api/plant/allocations', { asset_id: crane.id, employee_id: ravi.id })).status === 409)
await page.keyboard.press('Escape')
await sleep(400)

// an expense through the form, then once only
await tab('Expenses')
await page.evaluate(() => [...document.querySelectorAll('main button:not([role=tab])')].find((b) => b.textContent.trim() === 'Expense').click())
await page.waitForSelector('#xe-m')
await page.waitForFunction((c) => [...document.querySelectorAll('#xe-m option')].some((o) => o.textContent.includes(c)), { timeout: 15000 }, jcb.code)
await pick('#xe-m', jcb.code)
await setValue(page, '#xe-c', 'Spare parts')
await fill(page, '#xe-ds', 'Bucket teeth')
await fill(page, '#xe-q', '5')
await fill(page, '#xe-r', '1200')
await fill(page, '#xe-i', `JP-${stamp}`)
await top('Record the expense')
await waitForToast(page, 'EXP-')
await toastsGone(page)
const dup = await api(page, 'POST', '/api/plant/expenses', { asset_id: jcb.id, category: 'Spare parts', description: 'x', amount: 1, invoice_no: `JP-${stamp}` })
check('the same invoice cannot be entered twice', dup.status === 409)
await page.waitForFunction(() => /Total/.test(document.body.textContent) && /Spare parts/.test(document.body.textContent), { timeout: 10000 })
check('the register shows the fuel, the maintenance, the hire bill and the spares together', /Rental charges/.test(await text('main')) && /Fuel and diesel/.test(await text('main')))

// the dashboard counts what was just done
await tab('Dashboard')
await page.waitForFunction(() => /Operating cost/.test(document.body.textContent), { timeout: 10000 })
const dash = (await api(page, 'GET', `/api/plant/dashboard?date_from=${day(-30)}&date_to=${day(0)}`)).data
check('the dashboard cards are the records: hours, fuel, maintenance, cost', dash.cards.working_hours >= 8 && dash.cards.fuel >= 3600 && dash.cards.maintenance_cost >= 4500 && dash.cards.operating_cost >= 3600 + 4500 + 18000 + 6000, JSON.stringify(dash.cards))
check('recent activity lists what was done', /plant\./.test(JSON.stringify(dash.recent)))

// reports
await tab('Reports')
await page.waitForSelector('table[aria-label="Cost by machine"]')
check('cost by machine lists the JCB', (await text('table[aria-label="Cost by machine"]')).includes(jcb.code))
const href = await page.$eval('main a[href*="/api/plant/reports/fuel.xlsx"]', (a) => a.getAttribute('href'))
const xl = await page.evaluate(async (u) => (await fetch(u, { credentials: 'include' })).status, href)
const pdfHref = await page.$eval('main a[href*="/api/plant/reports/fuel.pdf"]', (a) => a.getAttribute('href'))
const pdf = await page.evaluate(async (u) => { const r = await fetch(u, { credentials: 'include' }); return [r.status, (await r.text()).slice(0, 4)] }, pdfHref)
check('the fuel report downloads as Excel and as PDF', xl === 200 && pdf[0] === 200 && pdf[1] === '%PDF', JSON.stringify([xl, pdf]))
await done()
